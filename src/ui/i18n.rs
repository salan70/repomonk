#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn skip_reasons_match_english_domain_keys() {
        let t = strings(UiLanguage::En);
        assert_eq!(
            t.skip_full(&SkipReason::TestFile, false),
            "test file (include_tests=false)"
        );
        assert_eq!(t.skip_short(Some(&SkipReason::TestFile), false), "test");
        assert_eq!(t.skip_full(&SkipReason::TestFile, true), "manually skipped");
        assert_eq!(
            t.skip_full(&SkipReason::LineTooLong { max_cols: 200 }, false),
            "line longer than 200 cols"
        );
    }

    #[test]
    fn japanese_skip_reasons_are_non_empty() {
        let t = strings(UiLanguage::Ja);
        assert!(!t.skip_full(&SkipReason::TestFile, false).is_empty());
        assert_eq!(t.skip_short(Some(&SkipReason::TestFile), false), "テスト");
        assert_eq!(t.open, "開く");
    }

    #[test]
    fn display_width_counts_cjk_as_two() {
        assert_eq!(display_width("ab"), 2);
        assert_eq!(display_width("開く"), 4);
    }
}
