impl UiStrings {
    pub fn skip_full(&self, reason: &SkipReason, manual: bool) -> String {
        if manual {
            return self.skip_manual.to_string();
        }
        match reason {
            SkipReason::VcsOrDependencyDir => self.skip_vcs.into(),
            SkipReason::GeneratedOrLockFile => self.skip_generated.into(),
            SkipReason::Binary => self.skip_binary.into(),
            SkipReason::LineTooLong { max_cols } => self
                .skip_line_too_long
                .replace("{n}", &max_cols.to_string()),
            SkipReason::FileTooLarge { max_lines } => self
                .skip_file_too_large
                .replace("{n}", &max_lines.to_string()),
            SkipReason::TestFile => self.skip_test.into(),
            SkipReason::ConfigFile => self.skip_config.into(),
            SkipReason::FileTypeDisabled => self.skip_type_off.into(),
            SkipReason::NoChunks => self.skip_empty.into(),
            SkipReason::IoError(msg) => format!("{}{msg}", self.skip_io),
        }
    }

    pub fn skip_short(&self, reason: Option<&SkipReason>, manual: bool) -> &'static str {
        if manual {
            return self.skip_manual_short;
        }
        match reason {
            Some(SkipReason::VcsOrDependencyDir) => self.skip_vcs_short,
            Some(SkipReason::GeneratedOrLockFile) => self.skip_generated_short,
            Some(SkipReason::Binary) => self.skip_binary_short,
            Some(SkipReason::LineTooLong { .. }) => self.skip_line_too_long_short,
            Some(SkipReason::FileTooLarge { .. }) => self.skip_file_too_large_short,
            Some(SkipReason::TestFile) => self.skip_test_short,
            Some(SkipReason::ConfigFile) => self.skip_config_short,
            Some(SkipReason::FileTypeDisabled) => self.skip_type_off_short,
            Some(SkipReason::NoChunks) => self.skip_empty_short,
            Some(SkipReason::IoError(_)) => self.skip_io_short,
            None => self.skip_manual_short,
        }
    }

    pub fn skip_full_opt(&self, reason: Option<&SkipReason>, manual: bool) -> String {
        if manual {
            return self.skip_manual.to_string();
        }
        match reason {
            Some(r) => self.skip_full(r, false),
            None => self.skip_manual.to_string(),
        }
    }

    pub fn entry_reason(&self, key: &str) -> String {
        let mapped = match key {
            "bin" => self.flow_reason_bin,
            "bin (Cargo.toml)" => self.flow_reason_bin_cargo,
            "bin (package.json)" => self.flow_reason_bin_pkg,
            "main (package.json)" => self.flow_reason_main_pkg,
            "crate root" => self.flow_reason_crate_root,
            "graph" => self.flow_reason_graph,
            "app" => self.flow_reason_app,
            "selected in tree" => self.flow_reason_selected,
            _ => key,
        };
        mapped.to_string()
    }

    pub fn format_error(&self, err: &Error) -> String {
        match err {
            Error::PathNotFound(p) => format!("{}: {}", self.err_path_not_found, p.display()),
            Error::InvalidPath(p) => format!("{}: {}", self.err_invalid_path, p.display()),
            Error::InvalidInput(s) => format!("{}: {s}", self.err_invalid_input),
            Error::GitNotFound => self.err_git_not_found.to_string(),
            Error::GitClone(s) => format!("{}: {s}", self.err_git_clone),
            Error::Git(s) => format!("{}: {s}", self.err_git),
            Error::NoChunks => self.err_no_chunks.to_string(),
            Error::Database(e) => format!("{}: {e}", self.err_database),
            Error::Io(e) => format!("{}: {e}", self.err_io),
            Error::Terminal(s) => format!("{}: {s}", self.err_terminal),
            Error::PurgeCancelled => self.err_purge_cancelled.to_string(),
            Error::Config(s) | Error::Message(s) => s.clone(),
        }
    }
}

